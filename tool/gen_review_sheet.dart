import 'dart:io';

import 'i18n_lint.dart' as lint;

const defaultArbDir = 'res/values';
const defaultOutDir = 'docs/i18n';
const libRoot = 'lib';

const tier1Terms = [
  'welcome', 'restore', 'seed', 'backup', 'pin', 'auth', 'dashboard', 'home',
  'send', 'confirm', 'start', 'setup', 'onboarding',
];
const tier2Terms = [
  'receive', 'transaction', 'settings', 'security', 'exchange', 'trade',
  'buy', 'sell', 'address', 'node', 'contact', 'wallet_list', 'details',
  'monero_accounts', 'nodes', 'disclaimer', 'faq',
];

class Row {
  Row(this.key, this.screen, this.tier, this.english, this.current, this.flags);

  final String key;
  final String screen;
  final int tier;
  final String english;
  final String? current;
  final List<String> flags;
}

String screenOf(String path) {
  final segments = path.split('/');
  final screensIndex = segments.indexOf('screens');
  if (screensIndex >= 0 && screensIndex + 1 < segments.length) {
    return segments[screensIndex + 1];
  }
  final viewModelIndex = segments.indexOf('view_model');
  if (viewModelIndex >= 0 && viewModelIndex + 1 < segments.length) {
    return segments[viewModelIndex + 1];
  }
  if (segments.length > 2) return segments[2];
  return segments.isEmpty ? path : segments.last;
}

int tierOf(String screen) {
  final name = screen.toLowerCase();
  if (tier1Terms.any(name.contains)) return 1;
  if (tier2Terms.any(name.contains)) return 2;
  return 3;
}

Map<String, Set<String>> collectCallSites() {
  final callPattern = RegExp(r'S\.(?:of\(context\)|current)\.([A-Za-z0-9_]+)');
  final result = <String, Set<String>>{};
  for (final entity in Directory(libRoot).listSync(recursive: true)) {
    if (entity is! File || !entity.path.endsWith('.dart')) continue;
    if (entity.path.contains('/generated/')) continue;
    final source = entity.readAsStringSync();
    if (!source.contains('S.')) continue;
    final screen = screenOf(entity.path);
    for (final match in callPattern.allMatches(source)) {
      (result[match.group(1)!] ??= <String>{}).add(screen);
    }
  }
  return result;
}

List<String> flagsFor(String lang, String key, String? en, String? value) {
  final flags = <String>[];
  if (en == null) return ['stale'];
  if (value == null) return ['missing'];
  if (value.trim().isEmpty) return ['empty'];
  if (lint.placeholders(en).join() != lint.placeholders(value).join()) {
    flags.add('placeholder');
  }
  if (value == en && !lint.brandKeys.contains(key) && !lint.isProperNounLike(en)) {
    if (lint.scriptRanges.containsKey(lint.baseLang(lang))) flags.add('english');
  }
  if (!lint.hasScriptChars(value, lang) &&
      !lint.brandKeys.contains(key) &&
      !lint.isProperNounLike(en)) {
    flags.add('no-script');
  }
  if (en.startsWith(' ') != value.startsWith(' ') ||
      en.endsWith(' ') != value.endsWith(' ')) {
    flags.add('space');
  }
  if (en.length > 12) {
    final ratio = value.length / en.length;
    if (ratio < 0.4 || ratio > 2.5) flags.add('length');
  }
  return flags;
}

String escape(String value) =>
    value.replaceAll('|', r'\|').replaceAll('\n', ' ⏎ ').trim();

void buildSheet(String lang, bool gapsOnly, int? tierFilter,
    {required String arbDir, required String outDir}) {
  final sourcePath = '${defaultArbDir}/strings_${lint.sourceLang}.arb';
  final targetPath = '$arbDir/strings_$lang.arb';
  if (!File(sourcePath).existsSync() || !File(targetPath).existsSync()) {
    stderr.writeln('Missing ARB for "$lang"');
    exit(2);
  }

  final source = lint.readStrings(sourcePath);
  final target = lint.readStrings(targetPath);
  final callSites = collectCallSites();

  final rows = <Row>[];
  for (final entry in source.entries) {
    final screen = (callSites[entry.key] ?? {}).isEmpty
        ? '(unreferenced)'
        : (callSites[entry.key]!.toList()..sort()).take(2).join(', ');
    final flags = flagsFor(lang, entry.key, entry.value, target[entry.key]);
    if (gapsOnly && flags.isEmpty) continue;
    rows.add(Row(entry.key, screen, tierOf(screen), entry.value, target[entry.key], flags));
  }
  for (final key in target.keys.where((k) => !source.containsKey(k))) {
    rows.add(Row(key, '(not in English)', 3, '', target[key], ['stale']));
  }
  rows.sort((a, b) {
    final byTier = a.tier.compareTo(b.tier);
    if (byTier != 0) return byTier;
    final byScreen = a.screen.compareTo(b.screen);
    return byScreen != 0 ? byScreen : a.key.compareTo(b.key);
  });

  final filtered = tierFilter == null ? rows : rows.where((r) => r.tier == tierFilter).toList();
  final buffer = StringBuffer()
    ..writeln('# $lang review sheet')
    ..writeln()
    ..writeln('Generated by `dart tool/gen_review_sheet.dart --lang=$lang`. '
        'Edit `res/values/strings_$lang.arb`, never this file.')
    ..writeln()
    ..writeln('Tier 1 = onboarding, seed/backup, PIN, dashboard, send. '
        'Tier 2 = receive, transactions, settings, security, exchange. '
        'Tier 3 = everything else.')
    ..writeln();

  for (final tier in [1, 2, 3]) {
    final tierRows = filtered.where((r) => r.tier == tier).toList();
    if (tierRows.isEmpty) continue;
    buffer
      ..writeln('## Tier $tier (${tierRows.length} strings)')
      ..writeln()
      ..writeln('| key | screen | English | current | flags |')
      ..writeln('|---|---|---|---|---|');
    for (final row in tierRows) {
      buffer.writeln('| ${row.key} | ${escape(row.screen)} | ${escape(row.english)} '
          '| ${escape(row.current ?? '')} | ${row.flags.join(', ')} |');
    }
    buffer.writeln();
  }

  Directory(outDir).createSync(recursive: true);
  final suffix = [
    if (gapsOnly) 'gaps',
    if (tierFilter != null) 'tier$tierFilter',
  ].join('_');
  final outPath = '$outDir/review_$lang${suffix.isEmpty ? '' : '_$suffix'}.md';
  File(outPath).writeAsStringSync(buffer.toString());

  final byTier = {for (final t in [1, 2, 3]) t: filtered.where((r) => r.tier == t).length};
  stdout.writeln('$outPath: ${filtered.length} strings '
      '(tier1 ${byTier[1]}, tier2 ${byTier[2]}, tier3 ${byTier[3]})');
}

void main(List<String> args) {
  var langs = <String>[];
  var arbDir = defaultArbDir;
  var outDir = defaultOutDir;
  var gapsOnly = false;
  int? tierFilter;

  for (final arg in args) {
    if (arg == '--gaps-only') gapsOnly = true;
    final arbArg = RegExp(r'^--arb-dir=(.+)$').firstMatch(arg);
    if (arbArg != null) arbDir = arbArg.group(1)!;
    final outArg = RegExp(r'^--out-dir=(.+)$').firstMatch(arg);
    if (outArg != null) outDir = outArg.group(1)!;
    final langArg = RegExp(r'^--lang=(.+)$').firstMatch(arg);
    if (langArg != null) langs = langArg.group(1)!.split(',');
    final tierArg = RegExp(r'^--tier=(\d)$').firstMatch(arg);
    if (tierArg != null) tierFilter = int.parse(tierArg.group(1)!);
  }

  if (langs.isEmpty) {
    stderr.writeln('Usage: dart tool/gen_review_sheet.dart --lang=hi[,bn] [--gaps-only] [--tier=1]');
    exit(2);
  }
  for (final lang in langs) {
    buildSheet(lang, gapsOnly, tierFilter, arbDir: arbDir, outDir: outDir);
  }
}
